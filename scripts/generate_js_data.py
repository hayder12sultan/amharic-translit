#!/usr/bin/env python3
"""
Regenerate web/data.js from src/amharic_translit/data/fidel_table.py.

The browser demo is a static page with no build step and no backend, so it
needs its own copy of the mapping data in JS. Rather than hand-maintaining
two copies that can drift apart, this script generates the JS file
mechanically from the single Python source of truth. Run it again any time
fidel_table.py changes:

    python scripts/generate_js_data.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from amharic_translit.data.fidel_table import (  # noqa: E402
    GLOTTAL_FAMILY,
    GLOTTAL_SUFFIXES,
    ORDER_SUFFIXES,
    REGULAR_FAMILIES,
)

OUTPUT = ROOT / "web" / "data.js"

HEADER = """\
// AUTO-GENERATED by scripts/generate_js_data.py — do not hand-edit.
// Source of truth: src/amharic_translit/data/fidel_table.py
"""


def main() -> None:
    payload = {
        "orderSuffixes": ORDER_SUFFIXES,
        "glottalSuffixes": GLOTTAL_SUFFIXES,
        "regularFamilies": REGULAR_FAMILIES,
        "glottalFamily": GLOTTAL_FAMILY,
    }
    body = "const FIDEL_DATA = " + json.dumps(payload, ensure_ascii=False, indent=2) + ";\n"
    OUTPUT.write_text(HEADER + body, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)} ({len(REGULAR_FAMILIES)} families)")


if __name__ == "__main__":
    main()
